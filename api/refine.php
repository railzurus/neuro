<?php
/**
 * YandexGPT proxy: два режима редактуры.
 *
 *  - mode=affirmation (по умолчанию) — кнопка «Поправь текст»: превращает текст
 *    в позитивные аффирмации от первого лица. Результат видит пользователь.
 *  - mode=tts — техническая подготовка перед синтезом речи: ё, ударения,
 *    числа прописью, разбивка на фразы и TTS-разметка пауз/акцентов.
 *    Результат пользователю не показывается, он уходит прямо в SpeechKit.
 *
 * Принимает POST JSON { text, mode? } и возвращает { text: <отредактированный> }.
 * Ключ читается из config/secrets.php: сначала `gpt_api_key`, если его нет —
 * `speechkit_api_key` (на случай единого ключа со scope foundationModels).
 * При любой ошибке отвечает JSON-ошибкой — фронтенд тогда откатывается на
 * локальную нормализацию текста.
 *
 * Требования в Yandex Cloud:
 *  - у сервисного аккаунта роль `ai.languageModels.user`;
 *  - API-ключ со scope `yc.ai.foundationModels.execute` (покрывает и SpeechKit,
 *    и YandexGPT) либо `yc.ai.languageModels.execute`.
 */

header('X-Content-Type-Options: nosniff');

function rfail(int $code, string $message, $detail = null): void
{
    http_response_code($code);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode(['error' => $message, 'detail' => $detail], JSON_UNESCAPED_UNICODE);
    exit;
}

if (($_SERVER['REQUEST_METHOD'] ?? 'GET') !== 'POST') {
    rfail(405, 'Method not allowed');
}

$configFile = __DIR__ . '/config/secrets.php';
if (!is_file($configFile)) {
    rfail(503, 'GPT not configured');
}
$config = require $configFile;
$trimChars = " \t\n\r\0\x0B\"'";
// Берём gpt_api_key, а если он пуст (пустая строка, не только null) — speechkit_api_key.
$gptKey = trim((string) ($config['gpt_api_key'] ?? ''), $trimChars);
$ttsKey = trim((string) ($config['speechkit_api_key'] ?? ''), $trimChars);
$apiKey = $gptKey !== '' ? $gptKey : $ttsKey;
$folderId = trim((string) ($config['folder_id'] ?? ''), $trimChars);
if ($apiKey === '' || $folderId === '' || strpos($apiKey, 'ВАШ') === 0) {
    rfail(503, 'GPT not configured');
}

$body = json_decode(file_get_contents('php://input'), true);
if (!is_array($body)) {
    rfail(400, 'Invalid JSON body');
}
$text = isset($body['text']) ? trim((string) $body['text']) : '';
if ($text === '') {
    rfail(400, 'Empty text');
}
// Тот же предел, что и у заказа: в GPT не должно уходить больше, чем мы
// вообще готовы озвучить (проверяем и здесь — эндпоинт открытый).
require_once __DIR__ . '/lib/textlimit.php';
if (!text_within_limit($text)) {
    rfail(413, 'Text too long');
}

$mode = (($body['mode'] ?? 'affirmation') === 'tts') ? 'tts' : 'affirmation';

// Обращение к YandexGPT платное, а эндпоинт открыт — ограничиваем частоту по IP,
// иначе им можно пользоваться как бесплатным GPT за наш счёт. Технический режим
// вызывается автоматически перед каждым синтезом, поэтому лимит у него выше.
require_once __DIR__ . '/lib/ratelimit.php';

// Потолок на весь сайт поверх персонального: у нарушителя с набором прокси
// адреса честно разные, и лимит по IP его не держит. Число подобрано с
// запасом относительно нынешней посещаемости — если живые пользователи
// начнут в него упираться, это попадёт в лог ошибок PHP, и предел надо
// будет поднять.
const REFINE_TOTAL_PER_HOUR = 300;
if (!rate_limit_total_allow('refine_' . $mode, REFINE_TOTAL_PER_HOUR, 3600)) {
    rfail(429, 'Service is busy, try later');
}

$quota = $mode === 'tts' ? 40 : 20;
if (!rate_limit_allow('refine_' . $mode, api_client_ip(), $quota, 3600)) {
    rfail(429, 'Too many requests, try later');
}

$affirmationPrompt = <<<'PROMPT'
Ты — редактор, специализирующийся на трансформации текстов в позитивные аффирмации от первого лица. Твоя задача — отредактировать предоставленный текст так, чтобы он соответствовал следующим правилам:

1. Все предложения должны передавать восприятие и действия рассказчика от первого лица единственного числа (я, мне, меня, мой, моя и т.п.), но строго избегай начинать каждое предложение с местоимения «Я». Используй разнообразные синтаксические конструкции: глаголы в 1‑м лице без подлежащего («Вижу…», «Слышу…», «Чувствую…»), обороты с «мне», «у меня», «передо мной», «в моей голове», «мои руки» и т.д. Начало текста может быть с «Я», но далее делай повествование естественным, без механического повторения.

2. Время — только настоящее (настоящее длительное или простое), все утверждения позитивные и описывают идеальную жизнь автора.

3. В тексте должны быть задействованы все три системы восприятия:
   - Визуальная (зрительные образы, цвета, формы, свет, движения).
   - Аудиальная (звуки, голоса, интонации, ритмы, музыка).
   - Кинестетическая (телесные ощущения, прикосновения, эмоции, внутреннее чувство, температура, тяжесть/легкость).

4. Если какая-либо из систем отсутствует или упомянута недостаточно, добавь 1–2 коротких предложения, которые органично впишутся в смысл текста и восполнят этот пробел. Не изменяй общий смысл и не придумывай лишнего.

5. Исправь все орфографические, грамматические и пунктуационные ошибки в исходном тексте. Если текст уже соответствует всем условиям, дополнительных изменений не вноси (кроме возможного усиления недостающих ощущений). В итоге выдай только исправленный текст, без комментариев, объяснений или вступительных фраз.
PROMPT;

// Разметка sil<[мс]> и <[accented]> поддерживается SpeechKit в API v1 для
// формата text — то есть ровно в том запросе, который делает api/tts.php.
$ttsPrompt = <<<'PROMPT'
Ты — эксперт по подготовке текстов для синтеза речи (TTS), в том числе для Yandex SpeechKit, и специалист по медитативным текстам. Твоя задача — выполнить только техническую обработку предоставленного текста, чтобы он максимально хорошо озвучивался и звучал как медитация на расслабление: спокойно, размеренно, с естественной интонацией. Смысл текста менять нельзя: не перефразируй, не упрощай, не добавляй и не удаляй смысловые детали — вноси исключительно технические правки и минимальные стилистические корректировки, нужные именно для медитативной подачи.
Выполни следующие шаги:

1. Замени «е» на «ё» только там, где это необходимо по правилам русского языка и критично для правильного произношения.
2. В словах-омографах явно укажи ударение с помощью знака «+» перед ударной гласной (например, «зам+ок»). Если омографов нет — этот шаг пропусти.
3. Раскрой все сокращения и запиши числа прописью (например, «д. 15» → «дом пятнадцать», «10 руб.» → «десять рублей»).
4. Разбей текст на короткие фразы длиной не более 250 символов; каждая фраза должна быть законченным смысловым отрезком. При этом выстраивай фразы так, чтобы их ритм подходил для медитации: старайся заканчивать отрезки на спокойных, «закрытых» словах, избегай обрыва на предлогах и союзах.
5. Если в тексте есть иностранные слова, которые система может произнести некорректно, предложи кириллическую запись с указанием ударения (если это улучшает восприятие). Если произношение не вызывает сомнений — оставь как есть.
6. Добавь TTS-разметку для пауз и акцентов:
   * Используй sil<[t]> для явных пауз (t — в миллисекундах). Для медитативного темпа ставь паузы 600–1200 мс между смысловыми блоками и 300–600 мс внутри длинных предложений.
   * Применяй <[accented]> только для слов, на которых важно сделать мягкое логическое ударение в медитации (ключевые образы, глаголы расслабления и т. п.). Избегай избыточных акцентов — медитация должна звучать спокойно.
7. Проверь грамматику и пунктуацию; исправь только фактические ошибки — без стилистических правок, кроме тех минимальных случаев, когда это критично для медитативного звучания (например, убрать излишне резкие формулировки, если они ломают спокойный тон, но без изменения смысла).

8. В итоге выдай только исправленный текст с применённой разметкой — без комментариев, объяснений или вступительных фраз. Текст должен быть готов к озвучиванию (TTS) и чтению.
PROMPT;

// Технический режим не должен обрезаться на полуслове: разметка и числа
// прописью заметно удлиняют ответ, а обрезанный текст ушёл бы прямо в синтез.
$payload = json_encode([
    'modelUri' => "gpt://{$folderId}/yandexgpt/latest",
    'completionOptions' => [
        'stream' => false,
        'temperature' => $mode === 'tts' ? 0.2 : 0.3,
        'maxTokens' => $mode === 'tts' ? '8000' : '2000',
    ],
    'messages' => [
        ['role' => 'system', 'text' => $mode === 'tts' ? $ttsPrompt : $affirmationPrompt],
        ['role' => 'user', 'text' => $text],
    ],
], JSON_UNESCAPED_UNICODE);

$ch = curl_init('https://llm.api.cloud.yandex.net/foundationModels/v1/completion');
curl_setopt_array($ch, [
    CURLOPT_POST => true,
    CURLOPT_POSTFIELDS => $payload,
    CURLOPT_RETURNTRANSFER => true,
    CURLOPT_HTTPHEADER => [
        'Authorization: Api-Key ' . $apiKey,
        'Content-Type: application/json',
    ],
    CURLOPT_TIMEOUT => $mode === 'tts' ? 90 : 45,
    CURLOPT_CONNECTTIMEOUT => 10,
]);
$response = curl_exec($ch);
$status = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
$curlErr = curl_error($ch);
curl_close($ch);

if ($response === false) {
    rfail(502, 'YandexGPT unreachable', $curlErr);
}
if ($status !== 200) {
    rfail($status ?: 502, 'YandexGPT error', $response);
}

$data = json_decode($response, true);
$refined = $data['result']['alternatives'][0]['message']['text'] ?? null;
if (!is_string($refined) || $refined === '') {
    rfail(502, 'Empty completion', $response);
}

header('Content-Type: application/json; charset=utf-8');
echo json_encode(['text' => trim($refined)], JSON_UNESCAPED_UNICODE);
